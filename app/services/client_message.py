"""Черновик сообщения клиенту для аналитика.

Аналитик пишет коротко, для себя: «нужна ОСВ 62, выручка не бьётся с БКИ». Модель предлагает
вежливый понятный текст для клиента, аналитик читает, правит и сам отправляет запрос.

Ограничения: внутреннюю кухню клиенту не раскрываем (бюро кредитных историй, скоринг, баллы, пороги,
подозрения), новых чисел и обещаний не добавляем. Ответ модели, нарушивший правило, отбрасывается —
аналитик получает заранее написанный шаблон для выбранного документа. Модель выключена — тоже шаблон.
"""
from __future__ import annotations

from dataclasses import dataclass

from app.services import llm

